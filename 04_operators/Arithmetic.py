#Arithmetic Operators (+,-,*,/,//,%,**)
a = 12
b = 4
print(a+b) #addition
print(a-b) #subtraction
print(a*b) #multiplication
print(a/b) #division (gives float value i.e. 3.0)
print(a//b) #floor division (converts float value into integer value i.e. 3)
print(a%b) #modulus (gives remainder i.e. 0)
print(a**b) #exponential (power operator)
