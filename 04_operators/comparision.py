#Comparison Operators (==, !=, <, >, <=, >=)
#it gives output in boolean value i.e. True or False
a = 10
b = 20
print(a == b) #equal to
print(a != b) #not equal to
print(a < b) #less than
print(a > b) #greater than
print(a <= b) #less than or equal to
print(a >= b) #greater than or equal to


